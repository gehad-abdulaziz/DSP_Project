"""
Execution Engine — Runs real DSP modules with injected parameters.

Instead of importing and calling run() directly (which uses module-level globals),
this engine patches the module-level variables before calling run(), then restores
them after. This approach:
  1. Does NOT duplicate any DSP code.
  2. Does NOT modify the original source files.
  3. Passes user-chosen parameters into the real pipeline.
"""

import importlib
import io
import sys
import time
import traceback
from contextlib import redirect_stdout, redirect_stderr
from pathlib import Path
from dataclasses import dataclass, field
from typing import Optional
import shutil
import numpy as np

# Map of part number -> module path
MODULE_MAP = {
    1: "part1_dtft.dtft",
    2: "part2_convolution.convolution",
    3: "part3_audio_analysis.audio_analysis",
    4: "part4_audio_filtering.notch_audio",
    5: "part5_image_fourier.image_fourier",
    6: "part6_image_denoising.image_denoising",
}

PART_NAMES = {
    1: "DTFT (Discrete-Time Fourier Transform)",
    2: "Convolution & Difference Equations",
    3: "Audio Signal Analysis",
    4: "Audio Filtering (Notch Filter)",
    5: "2D Fourier Transform & Image Filtering",
    6: "Image Denoising & Evaluation",
}

# Parameters that live in config.py rather than the part module
CONFIG_PARAMS = {
    3: {"F_NOISE": "F_NOISE"},
    4: {},  # NOTCH_FREQUENCY_HZ reads config.F_NOISE at module level, we handle it
}


@dataclass
class StageResult:
    name: str
    status: str = "pending"  # pending, running, completed, failed
    duration: float = 0.0
    stdout: str = ""
    stderr: str = ""
    error: str = ""
    outputs: list = field(default_factory=list)  # paths to generated files
    metrics: dict = field(default_factory=dict)


@dataclass
class PartResult:
    part_num: int
    name: str
    status: str = "pending"
    duration: float = 0.0
    stdout: str = ""
    stderr: str = ""
    error: str = ""
    outputs: list = field(default_factory=list)
    metrics: dict = field(default_factory=dict)
    params_used: dict = field(default_factory=dict)


def _get_module(part_num: int):
    """Import (or re-import) the module for a given part."""
    module_path = MODULE_MAP[part_num]
    if module_path in sys.modules:
        return importlib.reload(sys.modules[module_path])
    return importlib.import_module(module_path)


def _patch_module(mod, params: dict, part_num: int):
    """Temporarily set module-level variables to user-chosen values.
    Returns a dict of original values so they can be restored."""
    import config as cfg

    originals = {}
    for key, val in params.items():
        # Special: F_NOISE in part 3 also needs to be set on config
        if part_num == 3 and key == "F_NOISE":
            originals[("config", "F_NOISE")] = cfg.F_NOISE
            cfg.F_NOISE = val
            continue
        # Part 4: NOTCH_FREQUENCY_HZ is set from config.F_NOISE at import time
        if part_num == 4 and key == "NOTCH_FREQUENCY_HZ":
            if hasattr(mod, "NOTCH_FREQUENCY_HZ"):
                originals[("module", key)] = getattr(mod, key)
                setattr(mod, key, val)
            continue
        if hasattr(mod, key):
            originals[("module", key)] = getattr(mod, key)
            setattr(mod, key, val)
    return originals


def _restore_module(mod, originals: dict):
    """Restore original module-level variables."""
    import config as cfg
    for location_key, orig_val in originals.items():
        location, key = location_key
        if location == "config":
            setattr(cfg, key, orig_val)
        elif location == "module":
            setattr(mod, key, orig_val)


def _collect_outputs(part_num: int) -> list:
    """Scan the output directory for files generated by this part."""
    import config as cfg
    out_dir = cfg.OUT_DIR / f"part{part_num}"
    if not out_dir.exists():
        return []
    files = sorted(out_dir.glob("*"))
    return [str(f) for f in files if f.is_file()]


def _parse_metrics(stdout: str, part_num: int) -> dict:
    """Extract numerical results from the captured stdout."""
    metrics = {}
    for line in stdout.split("\n"):
        line = line.strip()
        if not line:
            continue
        # Generic key-value extraction
        if ":" in line and any(c.isdigit() for c in line):
            # Try to capture meaningful lines
            if any(kw in line.lower() for kw in [
                "peak", "rms", "mse", "psnr", "snr", "error", "frequency",
                "sampling", "samples", "duration", "length", "output length",
                "reduction", "attenuation", "level", "energy", "bandwidth",
                "difference", "radius", "stable", "amplitude", "max",
                "gain", "pole", "zero", "w0"
            ]):
                key = line.split(":")[0].strip().lstrip("- ")
                value = ":".join(line.split(":")[1:]).strip()
                metrics[key] = value
    return metrics


def run_part(part_num: int, params: dict = None, run_id: str = None) -> PartResult:
    """
    Execute a single DSP part with optional parameter overrides.

    Args:
        part_num: 1-6
        params: dict of parameter overrides (or None for defaults)
        run_id: optional experiment identifier

    Returns:
        PartResult with status, outputs, metrics, etc.
    """
    import config as cfg

    result = PartResult(
        part_num=part_num,
        name=PART_NAMES.get(part_num, f"Part {part_num}"),
        params_used=params or {},
    )

    # If run_id is specified, redirect outputs to a unique directory
    original_out_dir = None
    if run_id:
        original_out_dir = cfg.OUT_DIR
        experiment_out = cfg.ROOT / "experiments" / run_id / "outputs"
        experiment_out.mkdir(parents=True, exist_ok=True)
        cfg.OUT_DIR = experiment_out

    try:
        result.status = "running"
        start = time.time()

        # Import the module
        mod = _get_module(part_num)

        # Patch parameters if provided
        originals = {}
        if params:
            originals = _patch_module(mod, params, part_num)

        # Capture stdout/stderr
        stdout_buf = io.StringIO()
        stderr_buf = io.StringIO()

        try:
            with redirect_stdout(stdout_buf), redirect_stderr(stderr_buf):
                mod.run()
            result.status = "completed"
        except Exception as e:
            result.status = "failed"
            result.error = traceback.format_exc()
        finally:
            # Restore originals
            if originals:
                _restore_module(mod, originals)

        result.duration = time.time() - start
        result.stdout = stdout_buf.getvalue()
        result.stderr = stderr_buf.getvalue()

        # Collect outputs from the right directory
        if run_id:
            out_dir = experiment_out / f"part{part_num}"
        else:
            out_dir = cfg.OUT_DIR / f"part{part_num}"

        if out_dir.exists():
            result.outputs = [str(f) for f in sorted(out_dir.glob("*")) if f.is_file()]

        result.metrics = _parse_metrics(result.stdout, part_num)

    finally:
        if original_out_dir is not None:
            cfg.OUT_DIR = original_out_dir

    return result


def run_all(params_per_part: dict = None, run_id: str = None) -> list:
    """
    Run all six parts sequentially.

    Args:
        params_per_part: {part_num: {param: value}} or None
        run_id: optional experiment identifier

    Returns:
        List of PartResult objects.
    """
    results = []
    for part_num in range(1, 7):
        params = (params_per_part or {}).get(part_num, None)
        result = run_part(part_num, params=params, run_id=run_id)
        results.append(result)
        if result.status == "failed":
            # Continue running other parts even if one fails
            pass
    return results
